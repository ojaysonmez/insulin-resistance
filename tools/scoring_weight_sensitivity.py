#!/usr/bin/env python3
"""Weight sensitivity of the use-case tiers. No model, no network.

Reads the same score files as scoring_aggregate.py and asks how robust each row's tier is.
Two checks:
  1. Random weights: many weight sets drawn uniformly from the simplex (UQ, C, S, R all >= 0, sum 1), with a fixed
     seed. For each row: the share of draws in each tier (bands from scoring_aggregate.TIER_BANDS) and the tier range.
  2. Near-default weights: draws from a Dirichlet distribution centred on the default weights (concentration 20, so each
     weight typically moves by about 0.05 to 0.08): the realistic 'what if the weights were a little different' check.
  3. D7 shift: the row's tier when D7 (patients per year, many bins unsourced) is one bin lower or higher, at the
     default weights.
Writes usecases/scoring/weight-sensitivity.md. A tier is 'robust' when it is the same in at least 90% of the draws.

Usage (project root):  python tools/scoring_weight_sensitivity.py [--root DIR] [--draws N] [--seed N]
"""
import argparse
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from scoring_aggregate import SCALE, WEIGHTS, compute, load_scores, tier  # noqa: E402

KEYS = ["UQ", "C", "S", "R"]
TIERS = ["A", "B", "C", "D"]


def draw(rng):
    x = [rng.expovariate(1.0) for _ in KEYS]
    t = sum(x)
    return {k: v / t for k, v in zip(KEYS, x)}


def draw_near(rng, conc=20.0):
    d = WEIGHTS["default"]
    x = [rng.gammavariate(conc * d[k], 1.0) for k in KEYS]
    t = sum(x)
    return {k: v / t for k, v in zip(KEYS, x)}


def comp(rec, w):
    return sum(w[k] * rec[k] for k in KEYS)


def main():
    ap = argparse.ArgumentParser(description="Weight sensitivity of the use-case tiers (no model).")
    ap.add_argument("--root", default=str(HERE.parent))
    ap.add_argument("--draws", type=int, default=5000)
    ap.add_argument("--seed", type=int, default=20261027)
    a = ap.parse_args()
    by = load_scores(a.root)[0]
    out = compute(by)
    rows = {r: v for r, v in out.items() if "composite" in v}
    rng = random.Random(a.seed)
    ws = [draw(rng) for _ in range(a.draws)]
    wn = [draw_near(rng) for _ in range(a.draws)]
    dflt = WEIGHTS["default"]
    res = []
    for r, v in rows.items():
        counts = {t: 0 for t in TIERS}
        for w in ws:
            counts[tier(comp(v, w))] += 1
        share = {t: counts[t] / a.draws for t in TIERS}
        near = sum(1 for w in wn if tier(comp(v, w)) == tier(comp(v, dflt))) / a.draws
        modal = max(TIERS, key=lambda t: share[t])
        seen = [t for t in TIERS if counts[t]]
        base = comp(v, dflt)
        d7 = v["dims"]["D7"]
        lo = dict(v); lo["C"] = max(d7 - 1, 0) / SCALE["D7"]
        hi = dict(v); hi["C"] = min(d7 + 1, SCALE["D7"]) / SCALE["D7"]
        res.append(dict(row=r, near=near, base=base, tier=tier(base), share=share, modal=modal, seen=seen,
                        robust=share[tier(base)] >= 0.9,
                        d7=d7, t_lo=tier(comp(lo, dflt)), t_hi=tier(comp(hi, dflt))))
    res.sort(key=lambda x: -x["base"])
    L = ["# Weight sensitivity of the tiers", "",
         "Generated by `tools/scoring_weight_sensitivity.py` (no model). Not a score; do not edit by hand.", "",
         f"Method: {a.draws} weight sets drawn uniformly from the simplex (UQ, C, S, R each >= 0, sum 1; seed {a.seed}), "
         "tiers as in `ranking.md` (A 0.60 or more, B 0.50 to 0.59, C 0.40 to 0.49, D below 0.40). Default weights: "
         "UQ 0.40, C 0.25, S 0.20, R 0.15. 'Robust' = the default tier holds in at least 90% of the uniform draws (a strict test: it includes extreme weights such as nearly all weight on one ingredient). 'Holds near default weights' = share of draws from a Dirichlet distribution centred on the default weights (concentration 20) that keep the default tier. "
         "D7 shift = tier at default weights if D7 (patients per year) is one bin lower or higher.", ""]
    nrob = sum(1 for x in res if x["robust"])
    L += [f"Rows with a complete score set: {len(res)}. Robust: {nrob}. Fragile: {len(res) - nrob}.", "",
          "| Row | Default composite | Default tier | % A | % B | % C | % D | Tiers seen | Robust | Holds near default weights % | D7 | Tier at D7-1 | Tier at D7+1 |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for x in res:
        s = x["share"]
        L.append(f"| {x['row']} | {x['base']:.3f} | {x['tier']} | {s['A']*100:.0f} | {s['B']*100:.0f} | {s['C']*100:.0f} | {s['D']*100:.0f} | {''.join(x['seen'])} | {'yes' if x['robust'] else 'no'} | {x['near']*100:.0f} | {x['d7']:g} | {x['t_lo']} | {x['t_hi']} |")
    fr = [x for x in res if not x["robust"]]
    nn = [x for x in res if x["near"] < 0.8]
    L += ["", f"Rows whose default tier holds in fewer than 80% of near-default draws: {len(nn)} ({', '.join(str(x['row']) for x in nn) or 'none'}).", "", "## Fragile rows (default tier holds in under 90% of the draws)", ""]
    if fr:
        for x in fr:
            L.append(f"- Row {x['row']}: default tier {x['tier']} ({x['base']:.3f}); modal tier under random weights {x['modal']} ({x['share'][x['modal']]*100:.0f}%); tiers seen {''.join(x['seen'])}.")
    else:
        L.append("- none")
    d7f = [x for x in res if x["t_lo"] != x["tier"] or x["t_hi"] != x["tier"]]
    L += ["", "## Rows whose tier changes if D7 moves by one bin", ""]
    if d7f:
        for x in d7f:
            L.append(f"- Row {x['row']}: D7 {x['d7']:g}; tier {x['tier']} -> {x['t_lo']} (one bin lower), {x['t_hi']} (one bin higher).")
    else:
        L.append("- none")
    p = Path(a.root) / "usecases" / "scoring" / "weight-sensitivity.md"
    p.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{len(res)} rows, {nrob} robust, {len(res) - nrob} fragile, {len(d7f)} change tier with D7 +-1; wrote {p.relative_to(a.root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
