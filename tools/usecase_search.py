#!/usr/bin/env python3
"""Retrieval step for the use-case additions (no model, standard library only).

Runs the short PubMed strings in usecases/postprandial-queries.json (relevance order, no date
window), fetches compact records (title, first author, journal, date, DOI, publication types),
marks PMIDs already cited in usecases-verified.md, and writes one candidates file with the
existing row titles and the table format, for a lean agent to read. It does not judge relevance,
read abstracts, or edit any deliverable.

Usage (from the project root):
  python tools/usecase_search.py
  python tools/usecase_search.py --queries usecases/postprandial-queries.json --out usecases/postprandial-candidates.md
Environment: NCBI_API_KEY (optional). Exit code: 0 = ran (check the Errors section), 2 = cannot run.
"""
import argparse
import json
import os
import re
import sys
import time
import urllib.parse
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_citations import http_get, scan_file  # noqa: E402
from watch_fetch import ESEARCH, fetch_records, pubmed_params  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
PRIORITY = [("guideline", 0), ("consensus", 0), ("practice guideline", 0), ("systematic review", 1),
            ("meta-analysis", 1), ("review", 2), ("randomized controlled trial", 3), ("clinical trial", 3)]


def rank(rec):
    types = " ".join(rec.get("pubtype", [])).lower()
    best = 5
    for key, val in PRIORITY:
        if key in types:
            best = min(best, val)
    year = re.search(r"(19|20)\d{2}", rec.get("date", ""))
    return (best, -(int(year.group(0)) if year else 0))


def existing_rows():
    out, header = [], ""
    f = ROOT / "usecases-verified.md"
    if not f.exists():
        return out, header
    for ln in f.read_text(encoding="utf-8", errors="ignore").splitlines():
        if ln.startswith("| # |"):
            header = ln.strip()
        m = re.match(r"^\|\s*(\d+)\s*\|", ln)
        if m:
            c = [x.strip() for x in ln.strip().strip("|").split("|")]
            if len(c) >= 6:
                out.append(f"{c[0]} {c[1][:70]} | {c[2][:70]} | {c[5][:28]}")
    return out, header


def main():
    ap = argparse.ArgumentParser(description="Retrieval step for the use-case additions (no model).")
    ap.add_argument("--queries", default="usecases/postprandial-queries.json")
    ap.add_argument("--out", default="usecases/postprandial-candidates.md")
    args = ap.parse_args()
    try:
        cfg = json.loads((ROOT / args.queries).read_text(encoding="utf-8"))
    except Exception as e:
        print("cannot read queries file:", e, file=sys.stderr)
        return 2
    delay = 0.12 if os.environ.get("NCBI_API_KEY") else 0.4
    per = cfg.get("per_topic", 20)
    errors, hits, counts = [], {}, {}
    for t in cfg["topics"]:
        try:
            params = pubmed_params({"db": "pubmed", "term": t["query"], "retmax": per, "retmode": "json"})
            status, body = http_get(ESEARCH + "?" + params)
            time.sleep(delay)
            res = json.loads(body).get("esearchresult", {})
            counts[t["id"]] = int(res.get("count", 0))
            hits[t["id"]] = res.get("idlist", [])
        except Exception as e:
            counts[t["id"]] = None
            hits[t["id"]] = []
            errors.append(f"{t['id']}: {e}")
    all_ids = sorted({p for ids in hits.values() for p in ids})
    recs, r_err = fetch_records(all_ids, delay)
    errors += r_err

    cited = set()
    f = ROOT / "usecases-verified.md"
    if f.exists():
        for ln, pmids, dois in scan_file(str(f)):
            cited |= pmids

    rows, header = existing_rows()
    L = ["# Use-case additions: candidates from PubMed (post-meal, post-load and stimulated insulin or C-peptide)", "",
         "Generated by `tools/usecase_search.py` (no model). Titles and metadata only; nothing here is read at abstract or full-text level. Records are in PubMed relevance order per topic and then listed guidelines, consensus statements and reviews first. `[in list]` marks a PMID already cited in `usecases-verified.md`. These are the records found by the short strings below, not a complete search.", ""]
    for t in cfg["topics"]:
        c = counts.get(t["id"])
        L.append(f"## {t['id']}: {t['topic']}")
        L.append(f"String: `{t['query']}`; PubMed hits: {c if c is not None else 'error'}; listed: {len(hits[t['id']])}")
        recs_t = sorted([p for p in hits[t["id"]] if p in recs], key=lambda p: rank(recs[p]))
        if not recs_t:
            L.append("(no records)")
        for p in recs_t:
            r = recs[p]
            mark = " [in list]" if p in cited else ""
            L.append(f"- PMID {p}; DOI {r['doi'] or 'none in PubMed'}; {r['first_author']}; {r['journal']} {r['date']}; {', '.join(r['pubtype'][:3])}{mark}")
            L.append(f"  {r['title']}")
        L.append("")
    L.append("## Existing rows (do not duplicate; id, patient type, test, status)")
    L += [f"- {r}" for r in rows]
    L.append("")
    L.append("## Table format of usecases-verified.md")
    L.append(header or "(header not found)")
    L.append("")
    L.append("## Errors")
    L += ([f"- {e}" for e in errors] if errors else ["(none)"])
    L.append("")
    out = ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L), encoding="utf-8")
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    print(f"wrote {out.relative_to(ROOT)}: {len(all_ids)} unique records, {len(errors)} error(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
