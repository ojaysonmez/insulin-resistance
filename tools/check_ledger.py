#!/usr/bin/env python3
"""Check the claim ledger against the readable files (no model, no network).

Checks (claims/CLAIM-LEDGER.md, "Open points"):
1. claims/claims.csv has the expected 16 columns, unique claim IDs and allowed status values.
2. Every use-case row in usecases-verified.md has a UC-nn ledger row, and no UC-nn row points to a missing use case.
3. Every PMID cited in merged-conclusion.md or usecases-verified.md appears in some ledger source_ids.
4. Every PMID in the ledger source_ids appears in one of the two readable files (else it is listed for review).
5. Every depends_on and conflicts claim ID that looks like a ledger ID exists.

Usage (project root):  python tools/check_ledger.py [--root DIR] [--out FILE]
Exit code 1 if any check in 1, 2 or 5 fails; 3 and 4 are reported as warnings.
"""
import argparse
import csv
import re
import sys
from pathlib import Path

COLUMNS = ["claim_id", "section", "claim_text", "kind", "source_ids", "read_level", "caveats", "status",
           "confidence", "search_log_ref", "reviewed_by", "reviewer_verdict", "conflicts", "depends_on",
           "last_checked", "changelog_ref"]
STATUSES = {"supported", "qualified", "disputed", "unverified", "superseded"}
PMID_RE = re.compile(r"(?<![\w./])(\d{7,8})(?![\d])")
# Cited in the readable files on purpose without a ledger source (retracted; cited as do-not-cite in UC-08).
EXCLUDE = {"24757230"}
ID_RE = re.compile(r"\b(?:BL\d|CONF-\d+|GL-\d+|EV-\d+|MEAS-\d+|TRI-\d+|ABS-\d+|UC-[A-Z]*-?\d+)\b")


def pmids(text):
    """PMIDs written as 'PMID 1234567', 'PMIDs 1, 2' or bare 7-8 digit numbers next to such a label."""
    found = set()
    for m in re.finditer(r"PMIDs?\s*:?\s*((?:\d{7,8}(?:\s*(?:,|and|;|/)\s*)?)+)", text):
        found.update(PMID_RE.findall(m.group(1)))
    return found


def main():
    ap = argparse.ArgumentParser(description="Check claims/claims.csv against the readable files.")
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    ap.add_argument("--out", default="claims/build/ledger-check.md")
    a = ap.parse_args()
    root = Path(a.root)
    errors, warnings = [], []

    with open(root / "claims" / "claims.csv", encoding="utf-8", newline="") as f:
        reader = csv.reader(f)
        header = next(reader)
        rows = list(reader)
    if header != COLUMNS:
        errors.append(f"header differs from the design: {header}")
    bad = [i + 2 for i, r in enumerate(rows) if len(r) != len(COLUMNS)]
    if bad:
        errors.append(f"rows with the wrong number of columns (file lines): {bad[:20]}")
    recs = [dict(zip(header, r)) for r in rows if len(r) == len(COLUMNS)]
    ids = [r["claim_id"] for r in recs]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        errors.append(f"duplicate claim IDs: {dup}")
    badst = sorted({(r["claim_id"], r["status"]) for r in recs if r["status"] not in STATUSES})
    if badst:
        errors.append(f"status values outside {sorted(STATUSES)}: {badst[:20]}")

    uv = (root / "usecases-verified.md").read_text(encoding="utf-8")
    mc = (root / "merged-conclusion.md").read_text(encoding="utf-8")
    uc_rows = {int(m) for m in re.findall(r"^\| (\d+) \|", uv, re.M)}
    uc_ids = {int(m) for m in re.findall(r"^UC-(\d+)$", "\n".join(ids), re.M)}
    if uc_rows - uc_ids:
        errors.append(f"use-case rows with no UC ledger row: {sorted(uc_rows - uc_ids)}")
    if uc_ids - uc_rows:
        errors.append(f"UC ledger rows with no use-case row: {sorted(uc_ids - uc_rows)}")

    idset = set(ids)
    dangling = sorted({(r["claim_id"], x) for r in recs for fld in ("depends_on", "conflicts")
                       for x in ID_RE.findall(r[fld]) if x not in idset})
    if dangling:
        errors.append(f"depends_on or conflicts name IDs that do not exist: {dangling[:30]}")

    led = set()
    for r in recs:
        led |= pmids(r["source_ids"]) | set(PMID_RE.findall(r["source_ids"]))
    doc = pmids(mc) | pmids(uv)
    miss = sorted(doc - led - EXCLUDE)
    extra = sorted(p for p in led - doc if p not in mc and p not in uv)
    if miss:
        warnings.append(f"{len(miss)} PMID(s) cited in the readable files but in no ledger source_ids: {', '.join(miss)}")
    if extra:
        warnings.append(f"{len(extra)} ledger PMID(s) not found in either readable file (may come from review files): {', '.join(extra)}")

    out = ["# Ledger check (generated by tools/check_ledger.py; do not edit by hand)", "",
           f"Rows: {len(rows)}. Use-case rows: {len(uc_rows)}. PMIDs in readable files: {len(doc)}; in ledger: {len(led)}.", "",
           "## Errors", ""] + ([f"- {e}" for e in errors] or ["- none"]) + ["", "## Warnings", ""] + ([f"- {w}" for w in warnings] or ["- none"])
    (root / a.out).parent.mkdir(parents=True, exist_ok=True)
    (root / a.out).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"ledger check: {len(errors)} error(s), {len(warnings)} warning(s); wrote {a.out}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
