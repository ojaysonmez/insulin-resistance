#!/usr/bin/env python3
"""Combined table of the stage 1 screening units (no model, standard library only).

Reads usecases/scoring/S*.json and writes usecases/scoring/screen-summary.md: one line per
row with its tier, the five screening scores, an index (mean of D1, D2, D3, D7 and stakes
rescaled to 0-1, nulls skipped) and the path to viability. Preliminary: D7 values are
screening estimates.

Usage (project root):  python tools/scoring_screen_summary.py [--root DIR]
"""
import argparse
import glob
import json
import sys
from pathlib import Path

DEFAULT_ROOT = Path(__file__).resolve().parent.parent
SCALE = {"D1": 4, "D2": 4, "D3": 4, "D7": 5, "S": 4}
ORDER = {"viable now": 0, "close": 1, "far": 2}


def index(r):
    v = [r[d] / SCALE[d] for d in SCALE if r.get(d) is not None]
    return sum(v) / len(v) if v else 0.0


def main():
    ap = argparse.ArgumentParser(description="Combined stage 1 screen table (no model).")
    ap.add_argument("--root", default=str(DEFAULT_ROOT))
    a = ap.parse_args()
    rows = {}
    for f in sorted(glob.glob(str(Path(a.root) / "usecases" / "scoring" / "S*.json"))):
        j = json.loads(Path(f).read_text(encoding="utf-8"))
        for s in j.get("scores", []):
            rows.setdefault(s["row"], {})[s["dimension"]] = s["score"]
        for t in j.get("tiers", []):
            rows.setdefault(t["row"], {})["tier"] = t["tier"]
        for p in j.get("path_to_viability", []):
            rows.setdefault(p["row"], {})["pv"] = f'{p["missing_piece"][:90]} ({p["type"]}, {p["effort"]})'
    if not rows:
        print("no S*.json files found", file=sys.stderr)
        return 2
    L = ["# Stage 1 screen summary (generated by tools/scoring_screen_summary.py; preliminary)", "",
         "Index = mean of D1, D2, D3, D7 and stakes rescaled to 0-1, nulls skipped. D7 values are screening estimates, mostly low confidence; stage 2 replaces them with researched values.", "",
         "| Tier | Row | Index | D1 | D2 | D3 | D7 | S | Missing piece (type, effort) |", "|---|---|---|---|---|---|---|---|---|"]
    for r, v in sorted(rows.items(), key=lambda kv: (ORDER.get(kv[1].get("tier"), 3), -index(kv[1]))):
        L.append(f'| {v.get("tier")} | {r} | {index(v):.2f} | {v.get("D1")} | {v.get("D2")} | {v.get("D3")} | {v.get("D7")} | {v.get("S")} | {v.get("pv", "")} |')
    out = Path(a.root) / "usecases" / "scoring" / "screen-summary.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    print("\n".join(L[5:]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
