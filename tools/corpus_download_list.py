#!/usr/bin/env python3
"""Write corpus/download-list.md: the articles you still need to save as PDFs, with clickable links. No model.

Reads corpus/corpus.csv and corpus/oa-check.csv. Part A lists articles that have an open copy a browser can usually
reach (open them, save the PDF); part B lists the closed ones (need library access). Each line gives the file name to save
as: corpus/fulltext/<ID>.pdf. Articles already stored are not listed. Regenerate any time:
python tools/corpus_download_list.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "corpus"


def rd(p):
    with p.open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def main():
    corpus = rd(CORPUS / "corpus.csv")
    oa = {r["ID"]: r for r in rd(CORPUS / "oa-check.csv")} if (CORPUS / "oa-check.csv").exists() else {}
    need_all = [r for r in corpus if r.get("Full text local", "") in ("none", "")]
    need = [r for r in need_all if oa.get(r["ID"], {}).get("action") != "inaccessible"]
    dead = [r for r in need_all if oa.get(r["ID"], {}).get("action") == "inaccessible"]
    import glob
    import json
    import re
    # rows whose scores cite each PMID (score files) and the rank of each row, so the most important downloads come first
    rows_of = {}
    for f in sorted(glob.glob(str(ROOT / "usecases" / "scoring" / "[UV]*.json"))):
        try:
            j = json.load(open(f, encoding="utf-8"))
        except Exception:
            continue
        for s in j.get("scores", []) or []:
            for pm in set(re.findall(r"PMID[:\s]*(\d{6,8})", json.dumps(s, ensure_ascii=False))):
                if isinstance(s.get("row"), int):
                    rows_of.setdefault(pm, set()).add(s["row"])
    rank = {}
    try:
        rank = {int(k): v for k, v in json.load(open(ROOT / "usecases" / "scoring" / "ranking.json", encoding="utf-8"))["ranks"]["default"].items()}
    except Exception:
        pass

    def rows_text(r):
        rs = set(rows_of.get(r.get("PMID", ""), set()))
        rs |= {int(x) for x in r.get("Use-case rows", "").split(",") if x.strip().isdigit()}
        if not rs:
            return "cited in the conclusion document only"
        best = min((rank.get(x, 99) for x in rs), default=99)
        return "scores for row " + ", ".join(str(x) for x in sorted(rs)) + (f" (best rank {best})" if best < 99 else "")

    def best_rank(r):
        rs = set(rows_of.get(r.get("PMID", ""), set())) | {int(x) for x in r.get("Use-case rows", "").split(",") if x.strip().isdigit()}
        return min((rank.get(x, 99) for x in rs), default=99)

    def line(r):
        o = oa.get(r["ID"], {})
        doi = r.get("DOI", "")
        links = []
        if o.get("best_url"):
            links.append(f"[open copy]({o['best_url']})")
        if doi:
            links.append(f"[DOI](https://doi.org/{doi})")
        if r.get("PMID"):
            links.append(f"[PubMed](https://pubmed.ncbi.nlm.nih.gov/{r['PMID']}/)")
        cites = len([x for x in r.get("Cited in", "").split(";") if x.strip()])
        return (f"- [ ] **{r['ID']}** {r.get('First author', '')} {r.get('Year', '')}, {r.get('Title', '')[:100]} "
                f"({rows_text(r)}; {cites} citing place(s)) "
                f"- save as `corpus/fulltext/{r['ID']}.pdf` - " + " | ".join(links))
    def key(r):
        return (best_rank(r), -len([x for x in r.get("Cited in", "").split(";") if x.strip()]), r["ID"])
    solid = ("gold", "diamond", "green", "hybrid")
    a = sorted([r for r in need if oa.get(r["ID"], {}).get("best_url") and oa[r["ID"]]["oa_status"] in solid], key=key)
    c = sorted([r for r in need if oa.get(r["ID"], {}).get("best_url") and oa[r["ID"]]["oa_status"] not in solid], key=key)
    b = sorted([r for r in need if not oa.get(r["ID"], {}).get("best_url")], key=key)
    L = ["# PDFs to download (generated by tools/corpus_download_list.py; do not edit)", "",
         f"{len(need)} article(s) have no local text. Save each PDF as `corpus/fulltext/<ID>.pdf` (the folder is git-ignored), "
         "then run `python tools/corpus_build.py --no-network` (or tell the session) to update the list. Papers behind the highest-ranked use cases come first; each line shows which rows its scores affect.", "",
         f"## A. Open copy with a clear open status (gold, diamond, green or hybrid), open it in your browser ({len(a)})", ""] + \
        [line(r) for r in a] + \
        ["", f"## B. 'Bronze' copy: free on the publisher page at some point, no open license; often paywalled now, try it and if it asks for payment treat it as closed ({len(c)})", ""] + \
        [line(r) for r in c] + \
        ["", f"## C. No open copy, needs library or institutional access ({len(b)})", ""] + [line(r) for r in b] + \
        ["", f"## D. ??? Inaccessible: tried by hand, not reachable or not found online; to be requested through a colleague ({len(dead)})", ""] + \
        [line(r) + (f" - note: {oa[r['ID']]['notes']}" if oa.get(r["ID"], {}).get("notes") else "") for r in sorted(dead, key=key)]
    (CORPUS / "download-list.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"download list: {len(a)} clear open copy, {len(c)} bronze (may be paywalled), {len(b)} closed")


if __name__ == "__main__":
    main()
