#!/usr/bin/env python3
"""Measure what the full-text reviews change: before (abstract level) versus after (full text). No model.

Reads usecases/scoring/ft-review/FT*.json (one file per batch of full-text reviews: per-paper verdicts, score proposals,
claim issues). 'Before' is the ranking snapshot usecases/scoring/ft-review/baseline-ranking.json (saved before any
full-text proposal was applied); 'after' is a what-if: the current scores with every open proposal applied to a COPY in
memory (nothing is written to the score files). A proposal is simulated only if the stored scores of that row and
dimension average to its `current`; otherwise it is listed as stale (already applied, or the score moved since).

Writes usecases/scoring/ft-review/impact.md (summary and tables) and impact.csv (one line per paper). Re-run after each
new batch; the comparison then covers all batches, so it can be used for later evaluations too.

Usage (project root):  python tools/ft_impact.py [--root DIR]
"""
import argparse
import csv
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from scoring_aggregate import SCALE, compute, load_scores, tier  # noqa: E402


def load_batches(d):
    out = []
    for f in sorted(d.glob("FT*.json")):
        try:
            out.append((f.stem, json.loads(f.read_text(encoding="utf-8"))))
        except Exception as e:
            print(f"{f.name}: not valid JSON ({e}); skipped")
    return out


def simulate(by, proposals):
    """Apply proposals to a copy of by; return (new_by, applied, stale)."""
    nb = {k: [list(x) for x in v] for k, v in by.items()}
    applied, stale = [], []
    for unit, p in proposals:
        row, dim, cur, new = p.get("row"), p.get("dimension"), p.get("current"), p.get("proposed")
        if new is None or not isinstance(row, int) or dim not in SCALE:
            continue
        ents = nb.get((row, dim))
        if not ents:
            stale.append((unit, p, "no stored score"))
            continue
        mean = sum(e[1] for e in ents) / len(ents)
        if abs(mean - cur) > 0.01:
            stale.append((unit, p, f"stored mean {mean:.2f} differs from current {cur}"))
            continue
        d = new - cur
        for e in ents:
            e[1] = min(max(e[1] + d, 0), SCALE[dim])
        applied.append((unit, p))
    return {k: [tuple(x) for x in v] for k, v in nb.items()}, applied, stale


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(HERE.parent))
    a = ap.parse_args()
    root = Path(a.root)
    d = root / "usecases" / "scoring" / "ft-review"
    batches = load_batches(d)
    if not batches:
        print("no FT*.json files yet")
        return 0
    papers, proposals, issues = [], [], []
    for unit, j in batches:
        for p in j.get("papers", []) or []:
            papers.append((unit, p))
        for p in j.get("proposals", []) or []:
            proposals.append((unit, p))
        for i in j.get("claim_issues", []) or []:
            issues.append((unit, i))
    by, *_ = load_scores(root)
    now = compute(by)
    base_path = d / "baseline-ranking.json"
    before = json.loads(base_path.read_text(encoding="utf-8"))["rows"] if base_path.exists() else {
        str(r): v for r, v in now.items()}
    nb, applied, stale = simulate(by, proposals)
    after = compute(nb)

    verdicts = {}
    for _, p in papers:
        verdicts[p.get("verdict", "?")] = verdicts.get(p.get("verdict", "?"), 0) + 1
    changed = sum(v for k, v in verdicts.items() if k in ("adds nuance", "contradicts"))
    n_prop = len([1 for _, p in proposals if p.get("proposed") is not None])
    deltas = [abs(p["proposed"] - p["current"]) for _, p in proposals if isinstance(p.get("proposed"), (int, float)) and isinstance(p.get("current"), (int, float))]

    with (d / "impact.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["batch", "ID", "PMID", "verdict", "rows_affected", "dimensions_affected", "proposals", "text_quality"])
        for unit, p in papers:
            n = len([1 for u, q in proposals if p.get("id") in (q.get("papers") or []) and q.get("proposed") is not None])
            w.writerow([unit, p.get("id"), p.get("pmid"), p.get("verdict"), ",".join(map(str, p.get("rows_affected", []))),
                        ",".join(p.get("dimensions_affected", [])), n, p.get("text_quality", "")])

    L = ["# Full-text impact: before (abstract level) versus after (full text)", "",
         "Generated by `tools/ft_impact.py`; do not edit. 'After' is a what-if on a copy: no score file is changed by this report. "
         "Before = `baseline-ranking.json` (snapshot taken before any full-text proposal).", "",
         "## Summary", "",
         f"- Batches: {len(batches)} ({', '.join(u for u, _ in batches)}); papers reviewed: {len(papers)}.",
         "- Verdicts: " + ", ".join(f"{k} {v}" for k, v in sorted(verdicts.items())) + f". Papers that add nuance or contradict: {changed} of {len(papers)} ({(100 * changed // max(len(papers), 1))}%).",
         f"- Score proposals (not null): {n_prop}; simulated: {len(applied)}; stale or not simulable: {len(stale)}; mean size {(sum(deltas) / len(deltas)) if deltas else 0:.2f} point(s).",
         f"- Claim issues raised for the deliverables: {len(issues)}.", ""]
    rows = sorted({int(r) for r in before} | {r for r in after})
    moved = []
    T = ["## Composite and tier by row (default weights)", "", "| Row | Before | Tier | After (what-if) | Tier | Change |", "|---|---|---|---|---|---|"]
    for r in rows:
        b = before.get(str(r), {}).get("composite", {}).get("default") if isinstance(before.get(str(r)), dict) else None
        af = after.get(r, {}).get("composite", {}).get("default")
        if b is None or af is None:
            continue
        tb, ta = tier(b), tier(af)
        if abs(af - b) > 0.0005 or tb != ta:
            T.append(f"| {r} | {b:.3f} | {tb} | {af:.3f} | {ta} | {af - b:+.3f}{' (tier change)' if tb != ta else ''} |")
            if tb != ta:
                moved.append(r)
    if len(T) == 4:
        T.append("| - | no row changes composite | | | | |")
    L += [f"- Rows whose tier would change: {', '.join(map(str, moved)) or 'none'}.", ""] + T + [""]
    L += ["## Proposals", "", "| Batch | Row | Dim | Current | Proposed | Confidence | Papers | Simulated |", "|---|---|---|---|---|---|---|---|"]
    st = {(u, p.get("row"), p.get("dimension")): why for u, p, why in stale}
    for u, p in proposals:
        if p.get("proposed") is None:
            continue
        sim = "yes" if any(u == x and p is q for x, q in applied) else "no: " + st.get((u, p.get("row"), p.get("dimension")), "")
        L.append(f"| {u} | {p.get('row')} | {p.get('dimension')} | {p.get('current')} | {p.get('proposed')} | {p.get('confidence', '')} | {', '.join(p.get('papers') or [])} | {sim} |")
    L += ["", "## Claim issues", ""] + [f"- {u} {i.get('paper', '')}: {i.get('where', '')}: {str(i.get('issue', ''))[:240]}" for u, i in issues]
    L += ["", "## Per paper", "", "See `impact.csv` (batch, ID, PMID, verdict, rows, dimensions, proposals, text quality)."]
    (d / "impact.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"impact: {len(papers)} papers, {n_prop} proposals ({len(applied)} simulated), tier changes {moved or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
